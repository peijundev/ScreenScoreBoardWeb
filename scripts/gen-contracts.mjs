// 生成前后端共享契约类型：设置字段（来自 server/state.js 的 DEFAULT_SETTINGS）与 op 名
// 运行: npm run gen:contracts
import { createRequire } from 'node:module';
import { writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const require = createRequire(import.meta.url);
const root = path.join(path.dirname(fileURLToPath(import.meta.url)), '..');
const { DEFAULT_SETTINGS } = require('../server/state.js');
const { OPS } = require('../server/ops.js');

function tsType(value) {
  if (Array.isArray(value)) {
    if (value.every((v) => typeof v === 'number')) return 'number[]';
    if (value.every((v) => typeof v === 'string')) return 'string[]';
    return 'unknown[]';
  }
  if (value === null) return 'string | null';
  if (typeof value === 'number') return 'number';
  if (typeof value === 'boolean') return 'boolean';
  if (typeof value === 'string') return 'string';
  return 'unknown';
}

const settingsLines = Object.entries(DEFAULT_SETTINGS).map(
  ([key, value]) => `  ${key}: ${tsType(value)};`,
);
const settingsOut = `// AUTO-GENERATED by scripts/gen-contracts.mjs — do not edit by hand.
export interface SettingsFields {
${settingsLines.join('\n')}
}
`;

const opNames = Object.values(OPS);
const opsOut = `// AUTO-GENERATED by scripts/gen-contracts.mjs — do not edit by hand.
export type OpName =
${opNames.map((name) => `  | '${name}'`).join('\n')};

export const OP_NAMES: readonly OpName[] = [
${opNames.map((name) => `  '${name}',`).join('\n')}
];
`;

writeFileSync(path.join(root, 'web/src/shared/settings.generated.ts'), settingsOut);
writeFileSync(path.join(root, 'web/src/shared/ops.generated.ts'), opsOut);
console.log(`生成完成：${Object.keys(DEFAULT_SETTINGS).length} 个设置字段，${opNames.length} 个 op`);
